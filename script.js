/* ==================================================
   PROGRAMET SIPAS DEPARTAMENTIT
   ================================================== */

function buildDepartmentBlocks(
  items = []
) {

  if (!items.length) {

    return "";

  }


  return items.map(group => `

    <div class="department-block">


      <h4 class="department-name">

        ${group.department}

      </h4>


      ${group.programs
        .map(program => `

          <div class="program-item">

            ${program}

          </div>

        `)
        .join("")}


    </div>

  `).join("");

}


